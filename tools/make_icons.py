#!/usr/bin/env python3
"""make_icons.py — the four listening-mode icons of the AirPods page, drawn anti-aliased and embedded as A8
(alpha-only) LVGL images that the page tints white.

    python3 tools/make_icons.py    -> app/aap_ctl/aap_icons.c, aap_icons.h

Why images and not LVGL shapes: the first version assembled each icon from rectangles, circles and 3x3 dots.
At 30 px that looked crude next to the stock springboard and next to iOS. Drawn at 16x and averaged down, the
edges are smooth, and an A8 image costs one 1 KB array per icon; the device's LVGL draws A8 with a recolour.

The set copies iOS (Settings > AirPods > Noise Control): ONE solid person (a head and a pair of shoulders),
and what sits around the HEAD says the mode -
    off           a thin, faint ring (halo)
    transparency  a ring of dots
    adaptive      no ring: the person stands a little to the left, two sparkles at the top right
    noise cancel  a thick, solid ring
The shoulders cut the bottom of the halo with a small gap, as in Apple's artwork. Dots sit on whole pixels
(a 2x2 block each) so they all read equally bright at 1x.
"""
import math, os
from PIL import Image, ImageDraw, ImageChops, ImageFilter

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "app", "aap_ctl")
N = 32                       # icon size in pixels
SS = 16                      # supersampling

HEAD_Y = 12.0                # head and halo centre (a whole pixel line, so snapped dots are symmetric)
HEAD_R = 4.3
SH_TOP, SH_BOT, SH_HW = 19.6, 28.6, 8.6      # shoulders: top, bottom, half width
GAP = 1.4                    # clear space between the shoulders and the halo


def canvas():
    return Image.new("L", (N * SS, N * SS), 0)


def circle(d, cx, cy, r, fill=255):
    d.ellipse([(cx - r) * SS, (cy - r) * SS, (cx + r) * SS, (cy + r) * SS], fill=fill)


def head(cx):
    m = canvas(); circle(ImageDraw.Draw(m), cx, HEAD_Y, HEAD_R); return m


def shoulders(cx, top=SH_TOP):
    """A wide dome with a flat bottom: a rounded rectangle cut off below SH_BOT."""
    m = canvas(); d = ImageDraw.Draw(m)
    d.rounded_rectangle([(cx - SH_HW) * SS, top * SS, (cx + SH_HW) * SS, (SH_BOT + 8) * SS], radius=6.0 * SS, fill=255)
    d.rectangle([0, SH_BOT * SS, N * SS, N * SS], fill=0)
    return m


def dilate(m, px):
    k = int(round(px * SS)) * 2 + 1
    return m.filter(ImageFilter.MaxFilter(k))


def ring(cx, r_out, r_in, cut, level=255):
    """The halo around the head, with the shoulders' clearance cut out of it."""
    m = canvas(); d = ImageDraw.Draw(m)
    circle(d, cx, HEAD_Y, r_out, level); circle(d, cx, HEAD_Y, r_in, 0)
    return ImageChops.subtract(m, cut)


def dots(cx, n, r, rad, cut):
    """n dots around the head; each centre snapped to a whole pixel (the corner of four pixels), so each dot
    covers the same 2x2 pixels. Dots that fall in the shoulders' clearance are left out."""
    m = canvas(); d = ImageDraw.Draw(m)
    for i in range(n):
        a = math.radians(-90 + 360.0 * i / n)
        x = round(cx + r * math.cos(a)); y = round(HEAD_Y + r * math.sin(a))
        if cut.getpixel((int(x * SS), int(y * SS))) > 0:
            continue
        circle(d, x, y, rad)
    return m


def sparkle(cx, cy, R, inner=0.24):
    """A four-pointed star."""
    m = canvas(); d = ImageDraw.Draw(m)
    pts = []
    for k in range(8):
        a = math.radians(-90 + 45 * k)
        r = R if k % 2 == 0 else R * inner
        pts.append(((cx + r * math.cos(a)) * SS, (cy + r * math.sin(a)) * SS))
    d.polygon(pts, fill=255)
    return m


def merge(*ms):
    out = canvas()
    for m in ms:
        out = ImageChops.lighter(out, m)
    return out


def person_with(halo_fn):
    cx = 16.0
    sh = shoulders(cx)
    cut = dilate(sh, GAP)
    return merge(head(cx), sh, halo_fn(cx, cut))


def adaptive():
    cx = 13.5                                # the person steps aside to make room for the sparkles
    sh = shoulders(cx, top=SH_TOP + 0.4)
    return merge(head(cx), sh, sparkle(24.2, 8.0, 5.4), sparkle(18.8, 3.4, 2.7))


ICONS = {
    # 1 off: thin, fainter halo
    1: person_with(lambda cx, cut: ring(cx, 9.2, 7.9, cut, level=190)),
    # 3 transparency: dots around the head
    3: person_with(lambda cx, cut: dots(cx, 14, 8.4, 1.05, cut)),
    # 4 adaptive: sparkles
    4: adaptive(),
    # 2 noise cancellation: thick solid halo
    2: person_with(lambda cx, cut: ring(cx, 9.6, 7.1, cut)),
}


def to_a8(m):
    return m.resize((N, N), Image.LANCZOS).tobytes()


def main():
    names = {1: "off", 3: "transparency", 4: "adaptive", 2: "noise_cancel"}
    with open(os.path.join(OUT, "aap_icons.h"), "w") as f:
        f.write("""/* aap_icons.h — GENERATED by tools/make_icons.py. Do not edit.
 *
 * The listening-mode icons as A8 (alpha only) images; the page tints them. */
#ifndef AAP_ICONS_H
#define AAP_ICONS_H

#include "lvgl/lvgl.h"

#define AAP_ICON_SIZE %d

/* mode: 1 off, 2 noise cancellation, 3 transparency, 4 adaptive; NULL for anything else */
const lv_image_dsc_t *aap_icon_mode(int mode);

#endif
""" % N)
    with open(os.path.join(OUT, "aap_icons.c"), "w") as f:
        f.write("/* aap_icons.c — GENERATED by tools/make_icons.py. Do not edit. */\n#include \"aap_icons.h\"\n\n")
        for mode, nm in names.items():
            data = to_a8(ICONS[mode])
            f.write("static const uint8_t ic_%s_px[] __attribute__((aligned(4))) = {\n" % nm)
            for i in range(0, len(data), 32):
                f.write("    " + ",".join("0x%02x" % c for c in data[i:i + 32]) + ",\n")
            f.write("};\nstatic const lv_image_dsc_t ic_%s = {\n"
                    "    .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .w = %d, .h = %d, .stride = %d },\n"
                    "    .data_size = %d, .data = ic_%s_px };\n\n" % (nm, N, N, N, len(data), nm))
        f.write("const lv_image_dsc_t *aap_icon_mode(int mode)\n{\n    switch (mode) {\n")
        for mode, nm in names.items():
            f.write("    case %d: return &ic_%s;\n" % (mode, nm))
        f.write("    default: return 0;\n    }\n}\n")
    # preview sheets next to the scratch files: smooth, and the real 1x pixels zoomed with no smoothing
    pdir = os.environ.get("ICON_PREVIEW_DIR", "/tmp")
    order = (1, 3, 4, 2)
    sheet = Image.new("RGB", (4 * 140, 140), (28, 28, 30))
    for i, mode in enumerate(order):
        a = ICONS[mode].resize((N * 4, N * 4), Image.LANCZOS)
        sheet.paste(Image.new("RGB", a.size, (255, 255, 255)), (i * 140 + 6, 6), a)
    sheet.save(os.path.join(pdir, "mode_icons.png"))
    px = Image.new("RGB", (4 * N, N), (28, 28, 30))
    for i, mode in enumerate(order):
        a = Image.frombytes("L", (N, N), to_a8(ICONS[mode]))
        px.paste(Image.new("RGB", (N, N), (255, 255, 255)), (i * N, 0), a)
    px.resize((px.width * 7, px.height * 7), Image.NEAREST).save(os.path.join(pdir, "mode_icons_1x.png"))
    print("wrote aap_icons.c / aap_icons.h")


main()
